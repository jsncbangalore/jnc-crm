let reportContent = '';

function appendHeader(title, isCommand = true, scriptName = '') {
  reportContent += `\n========================================================================\n`;
  reportContent += `${title}\n`;
  if (isCommand) {
    reportContent += `GENERATED BY SCRIPT ${scriptName} AT ${now}\n`;
  } else {
    reportContent += `SUMMARY (not a command output)\n`;
  }
  reportContent += `========================================================================\n`;
}

function runCmd(cmd, cwd = 'C:\\dev\\crm', envOverrides = {}, timeoutMs = 45000) {
  try {
    const output = execSync(cmd, {
      cwd,
      env: { ...process.env, ...envOverrides },
      encoding: 'utf8',
      stdio: ['pipe', 'pipe', 'pipe'],
      timeout: timeoutMs,
    });
    return output;
  } catch (err) {
    return (err.stdout || '') + (err.stderr || '') + `\n[COMMAND EXIT CODE ${err.status || 1}]`;
  }
}

