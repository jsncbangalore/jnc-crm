const fs = require('fs');
const path = require('path');

let Client;
try {
  Client = require('pg').Client;
} catch {
  Client = class MockClient {};
}

const secretsPath = process.env.SECRETS_FILE || path.resolve(__dirname, "../.env");
if (!fs.existsSync(secretsPath)) {
  console.error(`[LIVE STATUS FAIL] Missing secrets file ${secretsPath}`);
  process.exit(1);
}

const envContent = fs.readFileSync(secretsPath, 'utf8');
const secrets = {};
envContent.split('\n').forEach(line => {
  line = line.trim();
  if (!line || line.startsWith('#')) return;
  const idx = line.indexOf('=');
  if (idx !== -1) {
    let k = line.substring(0, idx).trim();
    let v = line.substring(idx + 1).trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
      v = v.substring(1, v.length - 1);
    }
    secrets[k] = v;
  }
});

const EXPECTED_PROJECT_REF = process.env.TEST_NEW_PROJECT_REF || secrets.NEW_PROJECT_REF || 'aybysdzuwwtqhnzhgiwp';
const OLD_PROJECT_REF = secrets.OLD_PROJECT_REF || 'hbzlelktcfagwvmyusvw';
const directUrl = process.env.TEST_DIRECT_URL || secrets.DIRECT_URL;

if (!directUrl) {
  console.error('[LIVE STATUS FAIL] DIRECT_URL missing in environment/live.env');
  process.exit(1);
}

// Strictly parse project ref from connection string username
let actualRef;
try {
  const parsedUrl = new URL(directUrl);
  const username = parsedUrl.username || '';
  const match = username.match(/^[^.]+\.([a-z0-9_-]+)$/i);

  if (!match || !match[1]) {
    console.error(`[PROJECT REF REFUSAL] Connection string username "${username}" has no project ref. Format must be "postgres.<ref>". Execution refused.`);
    process.exit(1);
  }

  actualRef = match[1];

  if (actualRef === OLD_PROJECT_REF) {
    console.error(`[PROJECT REF REFUSAL] Connection string username has OLD_PROJECT_REF "${actualRef}". Refusing execution on old database.`);
    process.exit(1);
  }

  if (actualRef !== EXPECTED_PROJECT_REF) {
    console.error(`[PROJECT REF REFUSAL] Connection string project ref "${actualRef}" does not match expected NEW_PROJECT_REF "${EXPECTED_PROJECT_REF}". Execution refused.`);
    process.exit(1);
  }
} catch (err) {
  console.error(`[PROJECT REF REFUSAL] Connection string URL invalid: ${err.message}`);
  process.exit(1);
}

const schemaPath = path.resolve(__dirname, '../apps/api/prisma/schema.prisma');
if (!fs.existsSync(schemaPath)) {
  console.error(`[LIVE STATUS FAIL] Missing schema file at ${schemaPath}`);
  process.exit(1);
}

const schemaContent = fs.readFileSync(schemaPath, 'utf8');
const expectedModels = schemaContent
  .split('\n')
  .map(line => line.trim())
  .filter(line => line.startsWith('model '))
  .map(line => line.split(/\s+/)[1])
  .filter(Boolean);

const expectedTables = [...expectedModels, '_prisma_migrations'].sort();

function getPgSslConfig(urlStr) {
  let sslmode = 'require';
  try {
    const parsed = new URL(urlStr);
    const mode = parsed.searchParams.get('sslmode');
    if (mode) sslmode = mode.toLowerCase();
  } catch {}

  if (sslmode === 'disable') {
    return false;
  }

  const sslConfig = {
    rejectUnauthorized: true,
  };

  const caPath = process.env.PG_CA_FILE || process.env.NODE_EXTRA_CA_CERTS;
  if (caPath && fs.existsSync(caPath)) {
    sslConfig.ca = fs.readFileSync(caPath, 'utf8');
  }

  return sslConfig;
}

const cleanUrl = directUrl.replace(/[\?\&]sslmode=[^&]+/g, '');
const client = new Client({
  connectionString: cleanUrl,
  ssl: getPgSslConfig(directUrl),
});

async function runLiveStatus() {
  const timestamp = new Date().toISOString();
  console.log(`GENERATED BY SCRIPT scripts/live-status.js AT ${timestamp}`);
  console.log('========================================================================');
  console.log(`CRM LIVE DATABASE STATUS REPORT (Project Ref: ${actualRef})`);
  console.log('========================================================================\n');

  try {
    await client.connect();

    // 1. Query: List Public Tables
    const sql1 = `SELECT tablename FROM pg_tables WHERE schemaname = 'public' ORDER BY tablename;`;
    console.log(`SQL EXECUTION [1]: ${sql1}`);
    const res1 = await client.query(sql1);
    console.log(`RAW ROWS (${res1.rows.length} rows):`);
    console.log(JSON.stringify(res1.rows, null, 2));
    console.log('');

    // 2. Query: Row Security for Public Tables
    const sql2 = `SELECT tablename, rowsecurity FROM pg_tables WHERE schemaname = 'public' ORDER BY tablename;`;
    console.log(`SQL EXECUTION [2]: ${sql2}`);
    const res2 = await client.query(sql2);
    console.log(`RAW ROWS (${res2.rows.length} rows):`);
    console.log(JSON.stringify(res2.rows, null, 2));
    console.log('');

    // 3. Query: Tables with Row Security Disabled
    const sql3 = `SELECT tablename FROM pg_tables WHERE schemaname = 'public' AND rowsecurity = false;`;
    console.log(`SQL EXECUTION [3]: ${sql3}`);
    const res3 = await client.query(sql3);
    console.log(`RAW ROWS (${res3.rows.length} rows):`);
    console.log(JSON.stringify(res3.rows, null, 2));
    console.log('');

    // 4. Query: Prisma Migrations
    const sql4 = `SELECT migration_name, finished_at FROM _prisma_migrations ORDER BY migration_name;`;
    console.log(`SQL EXECUTION [4]: ${sql4}`);
    const res4 = await client.query(sql4);
    console.log(`RAW ROWS (${res4.rows.length} rows):`);
    console.log(JSON.stringify(res4.rows, null, 2));
    console.log('');

    // 5. Self-Check Comparison
    const dbTables = res1.rows.map(r => r.tablename).sort();
    console.log('========================================================================');
    console.log('SCHEMA COMPARISON SELF-CHECK');
    console.log(`Database Public Tables Count: ${dbTables.length}`);
    console.log(`Schema Models + Migrations Count: ${expectedTables.length}`);

    const missingInDb = expectedTables.filter(t => !dbTables.includes(t));
    const extraInDb = dbTables.filter(t => !expectedTables.includes(t));

    if (missingInDb.length === 0 && extraInDb.length === 0 && dbTables.length === expectedTables.length) {
      console.log('SELF-CHECK RESULT: MATCH');
      console.log(`All ${dbTables.length} database tables match schema models + _prisma_migrations exactly.`);
      console.log('========================================================================\n');
    } else {
      console.error('SELF-CHECK RESULT: MISMATCH');
      if (missingInDb.length > 0) console.error(`Missing in DB: ${missingInDb.join(', ')}`);
      if (extraInDb.length > 0) console.error(`Extra in DB: ${extraInDb.join(', ')}`);
      console.log('========================================================================\n');
      await client.end();
      process.exit(1);
    }

    await client.end();
  } catch (err) {
    console.error(`[LIVE STATUS FAIL] Database query error: ${err.message}`);
    process.exit(1);
  }
}

runLiveStatus();
