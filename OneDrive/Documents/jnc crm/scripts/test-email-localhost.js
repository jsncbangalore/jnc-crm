const fs = require('fs');
const path = require('path');

function testEmailTemplatesForLocalhost() {
  const timestamp = new Date().toISOString();
  console.log(`GENERATED BY SCRIPT test-email-localhost.js AT ${timestamp}`);
  console.log('Running Email Template Localhost Sanitization Test...\n');

  process.env.NODE_ENV = 'production';
  process.env.FRONTEND_URL = 'https://app.example.com';

  const filesToScan = [
    path.join(__dirname, '..', 'apps', 'api', 'src', 'platform', 'platform.service.ts'),
    path.join(__dirname, '..', 'apps', 'api', 'src', 'auth', 'auth.service.ts'),
    path.join(__dirname, '..', 'apps', 'api', 'src', 'notifications', 'notifications.service.ts'),
  ];

  let violations = 0;

  for (const file of filesToScan) {
    if (!fs.existsSync(file)) continue;
    const content = fs.readFileSync(file, 'utf8');
    const relativePath = path.relative(path.join(__dirname, '..'), file);

    // Search for any hardcoded localhost in email HTML strings or template fallbacks
    const emailSectionRegex = /emailHtml|sendMail|resetUrl|loginUrl/g;
    const lines = content.split('\n');

    lines.forEach((line, idx) => {
      if ((line.includes('emailHtml') || line.includes('loginUrl') || line.includes('resetUrl')) && line.includes('localhost')) {
        console.error(`[ERROR] Violation in ${relativePath}:${idx + 1}: ${line.trim()}`);
        violations++;
      }
    });
  }

  if (violations === 0) {
    console.log('[PASS] ALL EMAIL TEMPLATES & DISPATCH URLS ARE CLEAN OF "localhost" IN PRODUCTION MODE!');
  } else {
    console.error(`[ERROR] FOUND ${violations} LOCALHOST VIOLATIONS IN EMAIL TEMPLATES!`);
    process.exit(1);
  }
}

testEmailTemplatesForLocalhost();
