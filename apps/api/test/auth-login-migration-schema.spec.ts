import * as fs from 'fs';
import * as path from 'path';
import { Logger } from '@nestjs/common';
import { validateEnvironment } from '../src/common/env-validation';
import { GlobalHttpExceptionFilter } from '../src/common/http-exception.filter';

describe('Production Auth Login & Schema Migration Tests', () => {
  describe('Prisma Schema and Migration Parity', () => {
    it('should verify User model in schema.prisma defines isDemo', () => {
      const schemaPath = path.resolve(__dirname, '../prisma/schema.prisma');
      const schemaContent = fs.readFileSync(schemaPath, 'utf8');
      
      const userModelMatch = schemaContent.match(/model User\s*\{[\s\S]*?\n\}/);
      expect(userModelMatch).not.toBeNull();
      expect(userModelMatch![0]).toMatch(/isDemo\s+Boolean\s+@default\(false\)/);
    });

    it('should verify migration file exists for User.isDemo column', () => {
      const migrationFile = path.resolve(
        __dirname,
        '../prisma/migrations/20261119120000_add_user_is_demo/migration.sql'
      );
      expect(fs.existsSync(migrationFile)).toBe(true);
      const sqlContent = fs.readFileSync(migrationFile, 'utf8');
      expect(sqlContent).toContain('ALTER TABLE "User" ADD COLUMN IF NOT EXISTS "isDemo" BOOLEAN NOT NULL DEFAULT false;');
    });
  });

  describe('Production Environment Validation', () => {
    it('should allow production startup when MAIL_PROVIDER is resend without requiring SMTP host/user/pass', () => {
      const mockEnv: NodeJS.ProcessEnv = {
        NODE_ENV: 'production',
        PORT: '3000',
        DATABASE_URL: 'postgresql://postgres:postgres@localhost:5432/db',
        JWT_SECRET: 'production_valid_secret_key_32_characters_minimum!!',
        JWT_REFRESH_SECRET: 'production_valid_refresh_key_32_chars_min!!',
        ENCRYPTION_KEY: 'production_valid_encryption_key_32_chars!!',
        OTP_SECRET: 'production_valid_otp_secret_32_chars_min!!',
        FRONTEND_URL: 'https://admin.example.com',
        ALLOWED_ORIGINS: 'https://admin.example.com',
        EMAIL_FROM: 'notifications@example.com',
        MAIL_PROVIDER: 'resend',
        RESEND_API_KEY: 're_valid_test_key_1234567890',
        META_APP_SECRET: 'meta_secret_16chars_min!!',
      };

      const result = validateEnvironment(mockEnv);
      expect(result.isValid).toBe(true);
      expect(result.missingVariables).toEqual([]);
      expect(result.invalidVariables).toEqual([]);
    });

    it('should accept 32-character alphanumeric ENCRYPTION_KEY generated by cloud providers', () => {
      const mockEnv: NodeJS.ProcessEnv = {
        NODE_ENV: 'production',
        PORT: '3000',
        DATABASE_URL: 'postgresql://postgres:postgres@localhost:5432/db',
        JWT_SECRET: 'production_valid_secret_key_32_characters_minimum!!',
        JWT_REFRESH_SECRET: 'production_valid_refresh_key_32_chars_min!!',
        ENCRYPTION_KEY: 'aB3dE5gH7jK9mN1pQ3sT5vW7yZ9bC1d3', // 32 alphanumeric characters
        OTP_SECRET: 'production_valid_otp_secret_32_chars_min!!',
        FRONTEND_URL: 'https://admin.example.com',
        ALLOWED_ORIGINS: 'https://admin.example.com',
        EMAIL_FROM: 'notifications@example.com',
        MAIL_PROVIDER: 'resend',
        RESEND_API_KEY: 're_valid_test_key_1234567890',
        META_APP_SECRET: 'meta_secret_16chars_min!!',
      };

      const result = validateEnvironment(mockEnv);
      expect(result.isValid).toBe(true);
      expect(result.invalidVariables).toEqual([]);
    });

    it('should refuse startup if ENCRYPTION_KEY is shorter than 32 characters', () => {
      const mockEnv: NodeJS.ProcessEnv = {
        NODE_ENV: 'production',
        PORT: '3000',
        DATABASE_URL: 'postgresql://postgres:postgres@localhost:5432/db',
        JWT_SECRET: 'production_valid_secret_key_32_characters_minimum!!',
        JWT_REFRESH_SECRET: 'production_valid_refresh_key_32_chars_min!!',
        ENCRYPTION_KEY: 'too_short_key',
        OTP_SECRET: 'production_valid_otp_secret_32_chars_min!!',
        FRONTEND_URL: 'https://admin.example.com',
        ALLOWED_ORIGINS: 'https://admin.example.com',
        EMAIL_FROM: 'notifications@example.com',
        MAIL_PROVIDER: 'resend',
        RESEND_API_KEY: 're_valid_test_key_1234567890',
        META_APP_SECRET: 'meta_secret_16chars_min!!',
      };

      const result = validateEnvironment(mockEnv);
      expect(result.isValid).toBe(false);
      expect(result.invalidVariables.some(v => v.includes('ENCRYPTION_KEY'))).toBe(true);
    });
  });

  describe('Login 500 Sanitized Error Logging', () => {
    it('should log request ID, route, errorClass, and scrub secrets from stack trace on 500', () => {
      const logs: string[] = [];
      const originalError = Logger.prototype.error;
      Logger.prototype.error = function (msg: any) {
        logs.push(String(msg));
      };

      try {
        const filter = new GlobalHttpExceptionFilter();
        const mockRequest: any = {
          method: 'POST',
          url: '/api/v1/auth/login',
          route: { path: '/api/v1/auth/login' },
          headers: { 'x-request-id': 'req-test-trace-id-9988' },
          ip: '127.0.0.1',
        };

        let responseBody: any = null;
        let statusCode = 200;
        const mockResponse: any = {
          headers: {},
          setHeader(k: string, v: string) { this.headers[k.toLowerCase()] = v; },
          getHeader(k: string) { return this.headers[k.toLowerCase()]; },
          status(code: number) { statusCode = code; return this; },
          json(data: any) { responseBody = data; return data; },
        };

        const mockHost: any = {
          switchToHttp: () => ({
            getRequest: () => mockRequest,
            getResponse: () => mockResponse,
          }),
        };

        const simulatedError = new Error(
          'Postgres failure connecting to postgresql://user:sensitive_db_pass@supabase.co:5432/db with password="super_secret_user_pass"'
        );
        simulatedError.name = 'PrismaClientUnknownException';

        filter.catch(simulatedError, mockHost);

        expect(statusCode).toBe(500);
        expect(responseBody.statusCode).toBe(500);
        expect(responseBody.requestId).toBe('req-test-trace-id-9988');
        expect(responseBody.message).toBe('An internal database error occurred.');

        const matchingLog = logs.find(l => l.includes('req-test-trace-id-9988'));
        expect(matchingLog).toBeDefined();
        expect(matchingLog).toContain('[req-test-trace-id-9988]');
        expect(matchingLog).toContain('POST /api/v1/auth/login');
        expect(matchingLog).toContain('[errorClass=PrismaClientUnknownException]');
        expect(matchingLog).toContain('[prismaCode=NONE]');
        expect(matchingLog).not.toContain('sensitive_db_pass');
        expect(matchingLog).not.toContain('super_secret_user_pass');
      } finally {
        Logger.prototype.error = originalError;
      }
    });
  });
});
