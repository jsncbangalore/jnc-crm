/* --- READ-ONLY DATA INTEGRITY CHECK: COMPANY PROFILE BLANKS ---
 * Inspects local database (jnc_crm_dev) to identify tenants whose
 * address, GSTIN, or PAN is blank/null despite having issued invoices.
 *
 * SAFETY RULES:
 * - Read-only query.
 * - Strictly local execution only (refuses non-local databases).
 * - COUNTS ONLY: No tenant names, emails, phones, or personal data printed.
 * - Prints remediation instructions (AuditLog recovery / backup restore).
 */

const path = require('path');
const { PrismaClient } = require(path.join(__dirname, '../node_modules/@prisma/client'));

async function main() {
  console.log('================================================================');
  console.log('READ-ONLY CHECK: TENANTS WITH BLANK PROFILE & ISSUED INVOICES');
  console.log('================================================================\n');

  const dbUrl = process.env.DATABASE_URL || '';
  const isLocal =
    dbUrl.includes('localhost') ||
    dbUrl.includes('127.0.0.1') ||
    dbUrl.includes('jnc_crm_dev');

  if (!isLocal && process.env.NODE_ENV === 'production') {
    console.error('SAFETY REFUSAL: This script must NOT be run against live/production databases.');
    process.exit(1);
  }

  const prisma = new PrismaClient();

  try {
    const totalTenants = await prisma.tenant.count();

    // Find tenants with at least one issued invoice
    const tenantsWithInvoices = await prisma.tenant.findMany({
      where: {
        invoices: {
          some: {},
        },
      },
      select: {
        id: true,
        address: true,
        gstin: true,
        pan: true,
        _count: {
          select: {
            invoices: true,
          },
        },
      },
    });

    let blankAddressCount = 0;
    let blankGstinCount = 0;
    let blankPanCount = 0;
    let anyBlankCount = 0;

    for (const t of tenantsWithInvoices) {
      const isBlankAddress = !t.address || t.address.trim() === '';
      const isBlankGstin = !t.gstin || t.gstin.trim() === '';
      const isBlankPan = !t.pan || t.pan.trim() === '';

      if (isBlankAddress) blankAddressCount++;
      if (isBlankGstin) blankGstinCount++;
      if (isBlankPan) blankPanCount++;
      if (isBlankAddress || isBlankGstin || isBlankPan) {
        anyBlankCount++;
      }
    }

    console.log('--- SUMMARY METRICS (COUNTS ONLY - NO PII) ---');
    console.log(`Total Tenants in Database:                  ${totalTenants}`);
    console.log(`Tenants with Issued Invoices:               ${tenantsWithInvoices.length}`);
    console.log(`Tenants with Issued Invoices & Blank Address: ${blankAddressCount}`);
    console.log(`Tenants with Issued Invoices & Blank GSTIN:   ${blankGstinCount}`);
    console.log(`Tenants with Issued Invoices & Blank PAN:     ${blankPanCount}`);
    console.log(`Total Tenants with Any Blank Critical Field:  ${anyBlankCount}`);
    console.log('----------------------------------------------\n');

    if (anyBlankCount > 0) {
      console.log('REMEDIATION GUIDE:');
      console.log('1. Audit Log Recovery:');
      console.log('   Check the AuditLog table for action = "COMPANY_PROFILE_UPDATED":');
      console.log('   SELECT "tenantId", "afterState", "timestamp" FROM "AuditLog"');
      console.log('   WHERE action = \'COMPANY_PROFILE_UPDATED\'');
      console.log('   ORDER BY "timestamp" DESC;');
      console.log('   The "beforeState" object preserves previous address, GSTIN, and PAN values.\n');
      console.log('2. Backup Restoration:');
      console.log('   If blanking occurred prior to audit logging, restore the tenant profile');
      console.log('   from an earlier automated backup archive generated by `scripts/db-backup.js`.');
      console.log('   Use `scripts/db-restore-copy.js` to inspect a snapshot in an isolated throwaway DB.');
    } else {
      console.log('ALL CLEAR: Zero tenants with issued invoices have blank address, GSTIN, or PAN.');
    }
  } finally {
    await prisma.$disconnect();
  }
}

main().catch((err) => {
  console.error('[ERROR]', err);
  process.exit(1);
});
