const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const secretsPath = 'C:\\dev\\secrets\\live.env';
if (!fs.existsSync(secretsPath)) {
  console.error('Missing secrets file');
  process.exit(1);
}

const envContent = fs.readFileSync(secretsPath, 'utf8');
const secrets = {};
envContent.split('\n').forEach(line => {
  line = line.trim();
  if (!line || line.startsWith('#')) return;
  const idx = line.indexOf('=');
  if (idx !== -1) {
    let k = line.substring(0, idx).trim();
    let v = line.substring(idx + 1).trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
      v = v.substring(1, v.length - 1);
    }
    secrets[k] = v;
  }
});

function maskSecrets(str) {
  if (!str) return '';
  return str
    .replace(/postgresql:\/\/[^@]+@/g, 'postgresql://<MASKED>@')
    .replace(/aybysdzuwwtqhnzhgiwp:[^\s@&]+/g, 'aybysdzuwwtqhnzhgiwp:<MASKED>')
    .replace(/Password:\s+[^\s]+/gi, 'Password:            <MASKED>');
}

function runTest(cmd, envOverrides = {}) {
  const procEnv = { ...process.env, ...envOverrides };
  try {
    const stdout = execSync(cmd, { cwd: 'C:\\dev\\crm', env: procEnv, shell: true, stdio: ['pipe', 'pipe', 'pipe'] }).toString();
    return { exitCode: 0, output: maskSecrets(stdout) };
  } catch (err) {
    const stdoutStr = err.stdout ? err.stdout.toString() : '';
    const stderrStr = err.stderr ? err.stderr.toString() : '';
    const combined = (stdoutStr + '\n' + stderrStr).trim() || err.message;
    return { exitCode: err.status !== undefined ? err.status : 1, output: maskSecrets(combined) };
  }
}

