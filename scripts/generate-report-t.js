    const wrongUrl = secrets.DIRECT_URL.replace(/postgres\.[a-z0-9_-]+/i, 'postgres.wrongref');
    const wrongDbUrl = secrets.DATABASE_URL.replace(/postgres\.[a-z0-9_-]+/i, 'postgres.wrongref');
    const resB = runTest(s.path, { TEST_DIRECT_URL: wrongUrl, TEST_DATABASE_URL: wrongDbUrl, ...(s.testEnv || {}) });
