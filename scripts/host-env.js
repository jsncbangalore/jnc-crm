const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const liveSecretsPath = 'C:\\dev\\secrets\\live.env';
if (!fs.existsSync(liveSecretsPath)) {
  console.error(`[HOST ENV FAIL] Live secrets file missing at ${liveSecretsPath}`);
  process.exit(1);
}

const liveContent = fs.readFileSync(liveSecretsPath, 'utf8');
const liveSecrets = {};
liveContent.split('\n').forEach(line => {
  line = line.trim();
  if (!line || line.startsWith('#')) return;
  const idx = line.indexOf('=');
  if (idx !== -1) {
    let k = line.substring(0, idx).trim();
    let v = line.substring(idx + 1).trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
      v = v.substring(1, v.length - 1);
    }
    liveSecrets[k] = v;
  }
});

let dbUrl = liveSecrets.DATABASE_URL;
if (!dbUrl) {
  console.error('[HOST ENV FAIL] DATABASE_URL missing in C:\\dev\\secrets\\live.env');
  process.exit(1);
}

// Ensure 6543 pooler URL with pgbouncer=true&connection_limit=5
try {
  const parsed = new URL(dbUrl);
  parsed.port = '6543';
  parsed.searchParams.set('pgbouncer', 'true');
  parsed.searchParams.set('connection_limit', '5');
  dbUrl = parsed.toString();
} catch (err) {
  console.error(`[HOST ENV FAIL] Failed to parse DATABASE_URL: ${err.message}`);
  process.exit(1);
}

const jwtSecret = crypto.randomBytes(32).toString('hex');
const jwtRefreshSecret = crypto.randomBytes(32).toString('hex');
const encryptionKey = crypto.randomBytes(32).toString('base64');

const envLines = [
  '# Hostinger Production Environment File',
  '# Auto-generated by npm run host:env',
  `NODE_ENV=production`,
  `DATABASE_URL="${dbUrl}"`,
  `JWT_SECRET="${jwtSecret}"`,
  `JWT_REFRESH_SECRET="${jwtRefreshSecret}"`,
  `ENCRYPTION_KEY="${encryptionKey}"`,
  `FRONTEND_URL="${process.env.FRONTEND_URL || 'https://admin.example.com'}"`,
  `ALLOWED_ORIGINS="${process.env.ALLOWED_ORIGINS || 'https://admin.example.com'}"`,
  `TRUST_PROXY=1`,
  `EMAIL_FROM="${process.env.EMAIL_FROM || 'noreply@example.com'}"`,
  `SMTP_FROM="${process.env.EMAIL_FROM || 'noreply@example.com'}"`,
  '# Optional / Transactional Email Credentials',
  'SMTP_HOST=""',
  'SMTP_PORT="587"',
  'SMTP_USER=""',
  'SMTP_PASS=""',
];

const targetPath = 'C:\\dev\\secrets\\hostinger.env';
fs.writeFileSync(targetPath, envLines.join('\n'), 'utf8');

const varNames = envLines
  .filter(l => l && !l.startsWith('#'))
  .map(l => l.split('=')[0].trim());

console.log('========================================================================');
console.log('HOSTINGER ENV FILE GENERATED SUCCESSFULLY');
console.log('========================================================================');
console.log(`Target Path: ${targetPath}`);
console.log(`Total Lines: ${envLines.length}`);
console.log('Variable Names Included:');
varNames.forEach(v => console.log(`  - ${v}`));
console.log('------------------------------------------------------------------------');
console.log('SECURITY NOTICE: File contains production secrets. Do NOT check into git.');
console.log('Import into Hostinger Node.js Environment UI, then delete off local disk.');
console.log('========================================================================');
